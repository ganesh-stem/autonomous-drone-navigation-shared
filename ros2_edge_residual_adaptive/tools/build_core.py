"""
Builds edge_residual_adaptive/edge_residual_adaptive/core.py: the drone world (obstacles, wind, gusts, battery, noisy rays, 9 actions, wind compensation, safety filter)
without torch, pasted together from the sources of web3d_drones_edge/src. The ROS nodes import it, so they run the SAME environment as the training and as
web3d_drones_edge_residual_adaptive/server_edge_residual_adaptive.py (including that viewer's ~20% lower obstacle density, see OBSTACLE_DENSITY below).

    python tools/build_core.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parent / 'web3d_drones_edge' / 'src'
OUT = ROOT / 'edge_residual_adaptive' / 'edge_residual_adaptive' / 'core.py'
read = lambda n: (SRC / n).read_text(encoding='utf-8')

# server_edge_residual_adaptive.py sets D.COUNT_PROBS to this before it creates the world (mean obstacles per chunk 1.85 -> about 1.49). The same line is
# patched into core.py, so the ROS world is the same sky as the one the server flies in.
OBSTACLE_DENSITY = '[0.19, 0.30, 0.34, 0.17]'


def part(name, start, end=None):
    s = read(name)
    a = s.index(start)
    return s[a:s.index(end, a)] if end else s[a:]


header = '''"""
The drone world for the ROS 2 nodes: no torch, only numpy. Generated by tools/build_core.py from web3d_drones_edge/src
(drone_env.py, env_edge.py, env_edge_v2.py, edge_v3_common.py). Do not edit by hand.

Main things: EdgeDroneEnvV3 (the environment), shield_mask (the safety filter), StateStack (memory of the last k states), CONDITIONS (the weathers).
"""

import math
from collections import deque
from dataclasses import dataclass

import numpy as np

try:                                     # optional C++ ray casting (pybind11), built next to this file by tools/build_fastray.sh; numpy is used without it
    from . import fastray as _fastray
except ImportError:
    _fastray = None

'''
text = (header + '# ════════ drone environment (drone_env.py) ════════\n\n' + part('drone_env.py', '# ── World / obstacle generation')
        + '\n# ════════ weather, wind, battery (env_edge.py) ════════\n\n' + part('env_edge.py', '@dataclass(frozen=True)')
        + '\n\n# ════════ 9 actions, wind-scaled caution (env_edge_v2.py) ════════\n\n' + part('env_edge_v2.py', '# ── v2 begins here')
        + '\n\n# ════════ wind compensation, safety filter, state stack (edge_v3_common.py) ════════\n\n' + part('edge_v3_common.py', '# ── v3 common begins here', 'class ReplayWriter'))

lines, patched = text.split('\n'), False
for i, ln in enumerate(lines):
    if ln.startswith('COUNT_PROBS = '):
        lines[i] = f'COUNT_PROBS = {OBSTACLE_DENSITY}     # 0..3 obstacles per chunk, ~20% fewer than the training default: the density of server_edge_residual_adaptive.py'
        patched = True
        break
if not patched:
    raise SystemExit('COUNT_PROBS line not found in the sources: the density patch has to be updated')
text = '\n'.join(lines)

# Towers stay ROAD_INSET inside their chunk, because the viewer's roads and sidewalks run along the chunk borders (see server_edge_residual_adaptive.py: same shift).
ROAD_INSET = 18.0
append = '            boxes.append((x0, y0, z0, x0 + w, y0 + d, z1))'
if text.count(append) != 1:
    raise SystemExit('the boxes.append line of DroneEnv._chunk was not found: the road-inset patch has to be updated')
text = text.replace(append, f"""            if is_tower:                                     # keep towers off the viewer's roads (they run along the chunk borders); same arithmetic as the server's shift
                w, d = (x0 + w) - x0, (y0 + d) - y0
                x0 = min(max(x0, cx * CHUNK + {ROAD_INSET}), (cx + 1) * CHUNK - {ROAD_INSET} - w)
                y0 = min(max(y0, cy * CHUNK + {ROAD_INSET}), (cy + 1) * CHUNK - {ROAD_INSET} - d)
""" + append)

# Moving floating obstacles (flyers.py): the classes the ROS nodes use get the machinery. It does nothing until a node sets flyers_on = True
# (sim_node does, unless moving_obstacles:=false; camera_node and web_bridge copy the flag and the step number from /edge_residual/flyers).
text += """

# ════════ moving floating obstacles (flyers.py, shared with the viewer server) ════════
from . import flyers as _flyers                            # noqa: E402  (a sibling module: copied next to this file by tools/build_core.py)
_flyers.install(DroneEnv)                                  # the world the camera node and the web bridge rebuild from the seed
_flyers.install(EdgeDroneEnvV3)                            # the world the simulator steps
"""
OUT.write_text(text, encoding='utf-8')

# the cars of the city (traffic + parked cars) are shared with the server: the same file is copied into the package
CITY = ROOT.parent / 'web3d_drones_edge_residual_adaptive' / 'city_world.py'
(OUT.parent / 'city_world.py').write_text(CITY.read_text(encoding='utf-8'), encoding='utf-8')
(OUT.parent / 'flyers.py').write_text((ROOT.parent / 'web3d_drones_edge_residual_adaptive' / 'flyers.py').read_text(encoding='utf-8'), encoding='utf-8')
print('copied city_world.py and flyers.py')
print(f'wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)')
